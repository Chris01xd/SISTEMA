"""Training entrypoint for the demand forecasting models.

Usage:
    python -m app.artificial_intelligence.training.train_demand_forecaster

Trains against synthetic MCE traces generated by running the hybrid
simulation engine under randomized scenario parameters (see
docs/ARCHITECTURE.md section 7: real MCE datasets are rare/under-labeled,
so simulation-to-train is the primary data source; public ETL'd datasets
in app/datasets/etl.py supply baseline non-MCE demand patterns for
transfer/pretraining).
"""
from __future__ import annotations

import random
from pathlib import Path

import numpy as np

from app.artificial_intelligence.demand_forecasting import (
    WINDOW_SIZE,
    XGBoostDemandForecaster,
    build_sliding_windows,
)
from app.core.config import settings
from app.simulation.abm.model import HospitalMCEModel
from app.simulation.hybrid_engine import HybridSimulationEngine
from app.simulation.system_dynamics.sd_model import SDParameters


def generate_synthetic_trace(seed: int) -> tuple[np.ndarray, np.ndarray]:
    random.seed(seed)
    abm = HospitalMCEModel(
        n_beds_er=random.randint(15, 40),
        n_beds_icu=random.randint(5, 15),
        n_beds_ward=random.randint(20, 60),
        n_operating_rooms=random.randint(2, 6),
        n_doctors=random.randint(8, 20),
        n_surgeons=random.randint(3, 8),
        n_nurses=random.randint(15, 40),
        n_ambulances=random.randint(3, 10),
        severity_distribution={
            "minor": 0.4, "delayed": 0.3, "immediate": 0.2, "critical": 0.08, "expectant": 0.02
        },
        expected_victims=random.randint(30, 200),
        arrival_curve="surge_decay",
        arrival_window_minutes=random.choice([30, 60, 90]),
        timestep_minutes=1,
        seed=seed,
    )
    engine = HybridSimulationEngine(abm, SDParameters())
    results = engine.run(n_ticks=360)

    arrivals = np.diff([0] + [r.census["total_patients_seen"] for r in results]).astype(float)
    saturation = np.array([r.saturation_index for r in results])
    return arrivals, saturation


def main(n_traces: int = 25, output_dir: str | None = None) -> None:
    all_X, all_y = [], []
    for seed in range(n_traces):
        arrivals, saturation = generate_synthetic_trace(seed)
        X, y = build_sliding_windows(arrivals, saturation, window=WINDOW_SIZE)
        if len(X):
            all_X.append(X)
            all_y.append(y)

    X = np.concatenate(all_X, axis=0)
    y = np.concatenate(all_y, axis=0)
    X_flat = X.reshape(X.shape[0], -1)  # XGBoost needs 2D input

    model = XGBoostDemandForecaster()
    model.fit(X_flat, y)

    out_dir = Path(output_dir or settings.MODEL_ARTIFACT_DIR)
    out_dir.mkdir(parents=True, exist_ok=True)
    model.save(out_dir / "xgboost_demand_forecaster.json")
    print(f"Trained on {len(X)} samples from {n_traces} synthetic MCE traces.")
    print(f"Artifact saved to {out_dir / 'xgboost_demand_forecaster.json'}")


if __name__ == "__main__":
    main()
