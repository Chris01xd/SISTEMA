class MLDatasetInputComponent(Component):
    display_name = "ML Dataset Input"
    description = "Dataset and analysis parameters. A JSON object in the Chat Input overrides the fields below."
    icon = "database"
    name = "MLDatasetInput"

    inputs = [
        MessageTextInput(name="input_value", display_name="Parameters (JSON)", value="",
                         info='e.g. {"dataset": "mimic_icu", "target": "icu_flag", "cv_folds": 5}'),
        DropdownInput(name="dataset", display_name="Dataset", options=sorted(DATASETS), value="mimic_icu"),
        MessageTextInput(name="target", display_name="Target", value="", info="Empty = dataset default", advanced=True),
        DropdownInput(name="problem_type", display_name="Problem type", options=["classification"], value="classification"),
        IntInput(name="cv_folds", display_name="CV folds", value=5),
        FloatInput(name="test_size", display_name="Hold-out size", value=0.2, advanced=True),
        IntInput(name="random_state", display_name="Random state", value=42, advanced=True),
        BoolInput(name="explain_with_llm", display_name="Explain with LLM", value=True),
        DropdownInput(name="language", display_name="Language", options=["es", "en"], value="es"),
    ]
    outputs = [Output(display_name="Request", name="request", method="build_request")]

    def build_request(self) -> Data:
        ml_log("LANGFLOW", "Flow started")
        fields = {"dataset": self.dataset, "target": self.target or None, "problem_type": self.problem_type,
                  "cv_folds": self.cv_folds, "test_size": self.test_size, "random_state": self.random_state,
                  "explain_with_llm": self.explain_with_llm}
        overrides = parse_message(self.input_value)

        def build(_: dict) -> dict:
            if "_unparsable_message" in overrides:
                raise InvalidRequestError("The Chat Input must be empty or a JSON object with the analysis parameters")
            merged = {**{k: v for k, v in fields.items() if v is not None}, **overrides}
            language = merged.pop("language", self.language)
            return {"request": merged, "language": language, "started_at": time.time()}

        result = run_step("dataset_input", build, {"status": "ok"})
        self.status = result
        return Data(data=result)
