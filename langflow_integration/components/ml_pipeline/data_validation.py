from lfx.custom.custom_component.component import Component
from lfx.io import DataInput, Output
from lfx.schema.data import Data

from ai_module.ml.langflow_support import data_of, run_step, service


class MLDataValidationComponent(Component):
    display_name = "ML Data Validation"
    description = "Loads the registered dataset and validates target, columns, size and class balance; creates the run."
    icon = "shield-check"
    name = "MLDataValidation"

    inputs = [DataInput(name="request", display_name="Request", input_types=["Data"])]
    outputs = [Output(display_name="Validation", name="validation", method="validate_data")]

    def validate_data(self) -> Data:
        def step(request: dict) -> dict:
            report = service().validate(request["request"])
            report["language"] = request.get("language", "es")
            report["started_at"] = request.get("started_at")
            return report

        result = run_step("data_validation", step, data_of(self.request))
        self.status = result
        return Data(data=result)
