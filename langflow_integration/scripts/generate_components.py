FILES["explanation.py"] = header("ML Explanation", "BoolInput, DataInput, Output") + '''

class MLExplanationComponent(Component):
    display_name = "ML Explanation"
    description = ("Deterministic selection reason from the real metrics, plus an optional LLM explanation "
                   "(AI_LLM_* settings). The LLM cannot change the selected model.")
    icon = "message-square-text"
    name = "MLExplanation"

    inputs = [
        DataInput(name="validation", display_name="Validation", input_types=["Data"]),
        DataInput(name="selection", display_name="Best model", input_types=["Data"]),
        DataInput(name="comparison", display_name="Ranking", input_types=["Data"]),
        DataInput(name="cross_reference", display_name="Cross reference", input_types=["Data"]),
        DataInput(name="statistics", display_name="Statistical tests", input_types=["Data"]),
        BoolInput(name="use_llm", display_name="Use LLM", value=True, info="Also requires explain_with_llm in the request"),
    ]
    outputs = [Output(display_name="Explanation", name="explanation", method="explain")]

    def explain(self) -> Data:
        def step(validation: dict, selection: dict, comparison: dict, cross_ref: dict, statistics: dict) -> dict:
            use_llm = bool(self.use_llm and validation.get("explain_with_llm", True))
            return service().explain(selection, comparison, cross_ref, statistics, language=validation.get("language", "es"),
                                     use_llm=use_llm)

        result = run_step("explanation", step, data_of(self.validation), data_of(self.selection), data_of(self.comparison),
                          data_of(self.cross_reference), data_of(self.statistics))
        self.status = result
        return Data(data=result)
'''

FILES["analysis_output.py"] = header("ML Analysis Output", "DataInput, Output", message=True) + '''import json
import time

from ai_module.ml.log import ml_log

_REPORTS = ("validation", "eda", "preprocessing", "normal_models", "hybrid_models", "cross_validation", "evaluation",
            "cross_reference", "comparison", "statistics", "selection", "explanation")


class MLAnalysisOutputComponent(Component):
    display_name = "ML Analysis Output"
    description = ("Assembles the final JSON (status, models, ranking, best_model, CV, cross-reference, statistical tests, "
                   "EDA, hyper-parameters, interpretations, CRISP-DM, analysis, selection_reason).")
    icon = "file-json"
    name = "MLAnalysisOutput"

    inputs = [DataInput(name=n, display_name=n.replace("_", " ").title(), input_types=["Data"]) for n in _REPORTS]
    outputs = [Output(display_name="Result (JSON message)", name="message", method="build_message")]

    def build_message(self) -> Message:
        reports = [data_of(getattr(self, n, None)) for n in _REPORTS]

        def build(*r: dict) -> dict:
            started = r[0].get("started_at")
            return service().build_output(*r, duration_s=round(time.time() - started, 2) if started else None)

        result = run_step("analysis_output", build, *reports)
        if result.get("status") == "success":
            ml_log("LANGFLOW", f"Flow completed: {result['best_model']['name']} selected", run_id=result["run_id"])
            self.status = {k: result[k] for k in ("status", "run_id", "models_evaluated", "best_model")}
        else:
            ml_log("LANGFLOW", f"Flow completed with error: {result['error']['code']}", 30)
            self.status = result
        return Message(text=json.dumps(result, ensure_ascii=False, default=str))
'''


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "__init__.py").write_text("", encoding="utf-8")
    for name, code in FILES.items():
        (OUT / name).write_text(code, encoding="utf-8")
    print(f"{len(FILES)} components written to {OUT}")


if __name__ == "__main__":
    main()
