def _f(value: float | None) -> float:
    return float("nan") if value is None else float(value)


def selection_reason(best: dict[str, Any], comparison: dict[str, Any], cross_ref: dict[str, Any], cfg: dict[str, Any], language: str = "es",
                     statistics: dict[str, Any] | None = None) -> str:
    t = _T.get(language, _T["es"])
    ranking = comparison["ranking"]
    m = best["metrics"]
    xr = cross_ref["models"][best["key"]]
    primary = cfg["primary_metric"].upper().replace("_", "-")
    other = "pr_auc" if cfg["primary_metric"] == "roc_auc" else "roc_auc"
    margin = ""
    if len(ranking) > 1:
        runner = ranking[1]
        margin = t["margin"].format(diff=best["final_score"] - runner["final_score"], runner=runner["model"], runner_score=runner["final_score"])
    parts = [
        t["lead"].format(name=best["name"], type=t["type"][best["type"]], n=len(ranking), score=best["final_score"], margin=margin),
        t["cv"].format(folds=cfg["cv_folds"], primary=primary, cv_mean=_f(m["cv_mean"]), cv_std=_f(m["cv_std"]), stability=t[xr["stability"]],
                       f1=_f(m["cv_metrics"].get("f1")), other=other.upper().replace("_", "-"), other_value=_f(m["cv_metrics"].get(other))),
        t["holdout"].format(primary=primary, test=_f(m["test_score"]), train=_f(m["train_score"]), gap=_f(m["overfitting_gap"]),
                            diff=_f(xr["cv_vs_test_difference"]), generalization=t[xr["generalization"]]),
        (t["overfit_bad"] if xr["overfitting"] else t["overfit_ok"]).format(cv_gap=_f(m["cv_overfitting_gap"])),
    ]
    cm = cross_ref["cross_model"]
    if cm.get("best_hybrid_by_cv") and cm.get("best_normal_by_cv"):
        parts.append(t["hybrid"].format(hybrid=cm["best_hybrid_by_cv"]["model"], hybrid_cv=cm["best_hybrid_by_cv"]["cv_mean"],
                                        normal=cm["best_normal_by_cv"]["model"], normal_cv=cm["best_normal_by_cv"]["cv_mean"]))
    thr = cross_ref["thresholds"]
    flags = []
    if xr["overfitting"]:
        flags.append(t["flag_overfit"].format(gap=max(g for g in (xr["overfitting_gap"], xr["cv_overfitting_gap"]) if g is not None), thr=thr["overfitting_gap"]))
    if xr["stability"] == "unstable":
        flags.append(t["flag_unstable"].format(std=xr["cv_std"], thr=thr["instability_std"]))
    if xr["generalization"] == "inconsistent":
        flags.append(t["flag_inconsistent"].format(diff=xr["cv_vs_test_difference"], thr=thr["cv_holdout_gap"]))
    if flags:
        parts.append(t["flags"].format(flags="; ".join(flags)))
    if statistics:
        beaten = statistics["summary"]["models_significantly_worse_than_best"]
        parts.append(t["stats"].format(n=len(beaten), total=len(statistics["pairwise_vs_best"]), alpha=statistics["alpha"],
                                       evidence=t["evidence"][statistics["summary"]["evidence"]]))
    parts.append(t["caveat"])
    return " ".join(parts)


def _llm_payload(best: dict[str, Any], comparison: dict[str, Any], cross_ref: dict[str, Any], cfg: dict[str, Any], language: str) -> dict[str, Any]:
    return {
        "language": "Spanish" if language == "es" else "English",
        "best_model": {k: best[k] for k in ("name", "type", "final_score")} | {"metrics": {k: v for k, v in best["metrics"].items() if k != "confusion_matrix"}},
        "ranking": [{k: e[k] for k in ("rank", "model", "type", "final_score")} for e in comparison["ranking"]],
        "margin_over_runner_up": round(best["final_score"] - comparison["ranking"][1]["final_score"], 4) if len(comparison["ranking"]) > 1 else None,
        "score_config": comparison["score_config"],
        "winner_cross_reference": cross_ref["models"][best["key"]],
        "cross_model": cross_ref["cross_model"],
        "protocol": {"cv_folds": cfg["cv_folds"], "primary_metric": cfg["primary_metric"], "dataset": cfg["dataset"]},
        "statistical_tests": cfg.get("statistics_summary"),
    }


def llm_analysis(best: dict[str, Any], comparison: dict[str, Any], cross_ref: dict[str, Any], cfg: dict[str, Any],
                 ai_settings: AISettings, language: str = "es", model: Any = None) -> tuple[str | None, str | None]:
    """Returns (text, problem). ``text`` is None when the LLM is unavailable or its answer
    fails validation; ``problem`` then says why (safe to show)."""
    from ai_module.services.llm_factory import LLMConfigurationError, build_chat_model

    try:
        chat = model or build_chat_model(ai_settings)
    except LLMConfigurationError as exc:
        return None, str(exc)
    payload = _llm_payload(best, comparison, cross_ref, cfg, language)
    ml_log("LLM", "Generating explanation of the selected model", run_id=cfg.get("run_id"))
    try:
        reply = chat.invoke([("system", load_prompt_text("ml_explainer_system")), ("human", json.dumps(payload, ensure_ascii=False, default=str))])
        text = (reply.text if hasattr(reply, "text") else str(reply.content)).strip()
    except Exception as exc:  # provider errors of any type
        return None, f"LLM request failed ({type(exc).__name__})"
    if best["name"].lower() not in text.lower():
        return None, "LLM explanation discarded: it did not name the selected model"
    missing = ungrounded_numbers([text], payload)
    if missing:
        return None, f"LLM explanation discarded: numbers not present in the results ({', '.join(missing[:5])})"
    return text, None
