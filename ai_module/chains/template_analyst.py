"""Deterministic ``Analyst`` used when no LLM is configured, when the LLM fails, or when its
answer could not be grounded. Every statement is built from context values by code."""
from __future__ import annotations

from typing import Any

from ai_module.schemas.analysis import AnalysisOutput, Finding

_TEXT = {
    "es": {
        "answer": "Estado del gemelo digital: {color}. {extra}",
        "no_llm": "Respuesta generada por reglas deterministas (sin interpretación de un LLM).",
        "scenario": "En el escenario simulado la UCI alcanza una utilización media de {icu}% y la sala de {ward}% (estado {color}).",
        "baseline": "En operación normal la UCI tiene una utilización media de {icu}% y la sala de {ward}%.",
        "predicted": "Probabilidad estimada de requerir UCI: {p}; estancia estimada: {h} horas.",
        "observed": "En el dataset, {icu}% de {n} admisiones requirió UCI y la estancia mediana fue de {los} horas.",
        "rec_icu": "La UCI supera el 85% de utilización media en el escenario: valorar activar capacidad de expansión de UCI.",
        "caveat": "Datos de una muestra pequeña (demo pública); resultados ilustrativos.",
    },
    "en": {
        "answer": "Digital twin status: {color}. {extra}",
        "no_llm": "Answer generated by deterministic rules (no LLM interpretation).",
        "scenario": "In the simulated scenario the ICU reaches a mean utilization of {icu}% and the ward {ward}% (status {color}).",
        "baseline": "Under normal operation the ICU mean utilization is {icu}% and the ward {ward}%.",
        "predicted": "Estimated probability of needing ICU: {p}; estimated length of stay: {h} hours.",
        "observed": "In the dataset, {icu}% of {n} admissions needed ICU and the median length of stay was {los} hours.",
        "rec_icu": "ICU mean utilization exceeds 85% in the scenario: consider activating ICU surge capacity.",
        "caveat": "Small demo sample (public dataset); results are illustrative.",
    },
}


class TemplateAnalyst:
    name = "template"
    uses_llm = False

    def analyze(self, model_input: dict[str, Any]) -> AnalysisOutput:
        t = _TEXT.get(model_input.get("language", "es"), _TEXT["es"])
        ctx: dict[str, Any] = model_input["context"]
        observed = ctx["observed"]
        simulated = ctx.get("simulated") or {}
        run = simulated.get("scenario") or simulated["baseline"]
        findings = [
            Finding(source="observed", statement=t["observed"].format(
                icu=observed["icu_rate_pct"], n=observed["admissions"], los=observed["los_hours"]["median"])),
        ]
        key = "scenario" if "scenario" in simulated else "baseline"
        findings.append(Finding(source="simulated", statement=t[key].format(
            icu=run["icu"]["mean_utilization_pct"], ward=run["ward"]["mean_utilization_pct"], color=run["status_color"])))
        predicted = ctx.get("predicted")
        if predicted:
            findings.append(Finding(source="predicted", statement=t["predicted"].format(
                p=predicted["icu_probability"], h=predicted["predicted_los_hours"])))
        recommendations = [t["rec_icu"]] if "scenario" in simulated and run["icu"]["mean_utilization_pct"] >= 85 else []
        return AnalysisOutput(
            answer=t["answer"].format(color=run["status_color"], extra=t["no_llm"]),
            findings=findings,
            recommendations=recommendations,
            caveats=[t["caveat"], *ctx.get("warnings", [])],
        )
