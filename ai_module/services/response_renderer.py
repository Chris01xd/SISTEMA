"""Turns the twin context + the analysis into the final text answer.

The "facts" sections are rendered by code straight from the twin context, so the key
numbers are exact regardless of the LLM; the LLM's contribution is shown separately and
labeled as interpretation. This makes the origin of every value explicit to the reader."""
from __future__ import annotations

from typing import Any

from ai_module.schemas.analysis import AnalysisOutput

_LABELS = {
    "es": {
        "observed": "Datos observados (dataset público {name} v{version})",
        "obs_line": "{n} admisiones de {p} pacientes; ingreso a UCI {icu}%; estancia mediana {los} h (p90 {p90} h); mortalidad intrahospitalaria {mort}%.",
        "baseline": "Simulación — operación normal ({runs} corridas Monte Carlo, {h} h)",
        "scenario": "Simulación — escenario solicitado ({runs} corridas Monte Carlo, {h} h)",
        "sim_line": "Sala: {wc} camas, utilización media {wu}%, pico medio {wp}. UCI: {ic} camas, utilización media {iu}%, pico medio {ip}, "
                    "probabilidad de llenarse {ipr}%. Espera media por paciente {wait} h. Estado: {color}.",
        "surge_line": "Oleada: {n} pacientes adicionales en {d} h desde la hora {s}; mezcla ESI {mix}.",
        "predicted": "Predicción (modelo {version})",
        "pred_line": "Probabilidad de requerir UCI {p}; estancia estimada {h} h ({d} días). ROC-AUC en test {auc}.",
        "interpretation": "Interpretación ({who})",
        "llm": "generada por LLM {model}; no son datos",
        "rules": "reglas deterministas; no son datos",
        "recommendations": "Recomendaciones (apoyo a la decisión, no órdenes)",
        "caveats": "Limitaciones",
        "sources": {"observed": "observado", "simulated": "simulado", "predicted": "predicción", "assumption": "supuesto"},
    },
    "en": {
        "observed": "Observed data (public dataset {name} v{version})",
        "obs_line": "{n} admissions of {p} patients; ICU admission {icu}%; median length of stay {los} h (p90 {p90} h); in-hospital mortality {mort}%.",
        "baseline": "Simulation — normal operation ({runs} Monte Carlo runs, {h} h)",
        "scenario": "Simulation — requested scenario ({runs} Monte Carlo runs, {h} h)",
        "sim_line": "Ward: {wc} beds, mean utilization {wu}%, mean peak {wp}. ICU: {ic} beds, mean utilization {iu}%, mean peak {ip}, "
                    "probability of filling up {ipr}%. Mean wait per patient {wait} h. Status: {color}.",
        "surge_line": "Surge: {n} extra patients over {d} h from hour {s}; ESI mix {mix}.",
        "predicted": "Prediction (model {version})",
        "pred_line": "Probability of needing ICU {p}; estimated stay {h} h ({d} days). Test ROC-AUC {auc}.",
        "interpretation": "Interpretation ({who})",
        "llm": "generated by LLM {model}; not data",
        "rules": "deterministic rules; not data",
        "recommendations": "Recommendations (decision support, not orders)",
        "caveats": "Limitations",
        "sources": {"observed": "observed", "simulated": "simulated", "predicted": "predicted", "assumption": "assumption"},
    },
}


def _sim_lines(run: dict[str, Any], L: dict[str, Any]) -> list[str]:
    lines = [L["sim_line"].format(
        wc=run["ward"]["capacity"], wu=run["ward"]["mean_utilization_pct"], wp=run["ward"]["peak_occupancy_mean"],
        ic=run["icu"]["capacity"], iu=run["icu"]["mean_utilization_pct"], ip=run["icu"]["peak_occupancy_mean"],
        ipr=run["icu"]["probability_reach_capacity_pct"], wait=run["waiting"]["mean_wait_hours_per_patient"], color=run["status_color"],
    )]
    surge = run["scenario"]
    if surge.get("surge_patients"):
        lines.append(L["surge_line"].format(n=surge["surge_patients"], d=surge["surge_duration_hours"], s=surge["surge_start_hour"],
                                            mix=run["surge_esi_mix"]))
    return lines


def render_response(analysis: AnalysisOutput, context: dict[str, Any], language: str, *, uses_llm: bool, model_name: str) -> str:
    L = _LABELS.get(language, _LABELS["es"])
    obs = context["observed"]
    dataset = context["provenance"]["dataset"]
    parts: list[str] = [analysis.answer.strip(), ""]

    parts.append(f"## {L['observed'].format(name=dataset['name'], version=dataset['version'])}")
    parts.append("- " + L["obs_line"].format(n=obs["admissions"], p=obs["patients"], icu=obs["icu_rate_pct"], los=obs["los_hours"]["median"],
                                             p90=obs["los_hours"]["p90"], mort=obs["in_hospital_mortality_pct"]))
    simulated = context.get("simulated") or {}
    for key in ("baseline", "scenario"):
        run = simulated.get(key)
        if run:
            parts.append(f"\n## {L[key].format(runs=run['runs'], h=run['horizon_hours'])}")
            parts.extend("- " + line for line in _sim_lines(run, L))
    predicted = context.get("predicted")
    if predicted:
        auc = predicted["model"]["test_metrics"].get("icu_classifier", {}).get("roc_auc", "n/a")
        parts.append(f"\n## {L['predicted'].format(version=predicted['model']['version'])}")
        parts.append("- " + L["pred_line"].format(p=predicted["icu_probability"], h=predicted["predicted_los_hours"],
                                                  d=predicted["predicted_los_days"], auc=auc))

    who = L["llm"].format(model=model_name) if uses_llm else L["rules"]
    parts.append(f"\n## {L['interpretation'].format(who=who)}")
    parts.extend(f"- [{L['sources'].get(f.source, f.source)}] {f.statement}" for f in analysis.findings)
    if analysis.recommendations:
        parts.append(f"\n## {L['recommendations']}")
        parts.extend(f"- {r}" for r in analysis.recommendations)
    if analysis.caveats:
        parts.append(f"\n## {L['caveats']}")
        parts.extend(f"- {c}" for c in analysis.caveats)
    return "\n".join(parts).strip()
